"""Write docs/RESULTS.md: the perception-pipeline results, every row labelled with its pour mode, its pose source
(perception or simulator ground truth) and its seed split. Every number is read from a JSON in results/perception/.

    python scripts/results_table.py
"""
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from scripts.splits import SPLITS  # noqa: E402

R = "results/perception"
ROWS = [   # (file, what changed against the row above)
    ("eval_expert_truth_legacy_dev.json", "original pour: arm B holds the mug"),
    ("eval_expert_truth_setdown_legacy_dev.json", "set-down pour, retreat away from the drawer"),
    ("eval_perception_setdown_legacy_dev.json", "CNN poses; held objects keep the pre-grasp estimate"),
    ("eval_perception_calibrated_setdown_legacy_dev.json",
     "held bottle from forward kinematics + calibrated grasp offset; a pushed drawer is assumed shut"),
    ("test_expert_truth_setdown_legacy.json", "frozen configuration, run once on test"),
    ("test_perception_calibrated_setdown_legacy.json", "frozen configuration, run once on test (headline)"),
]
SUBGOALS = ("drawer_open", "plate_placed", "spoon_placed", "fork_placed", "poured", "bottle_placed", "mug_placed")


def wilson(k, n, z=1.96):
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def split_of(seeds):
    for name, rng in SPLITS.items():
        lo, hi = (int(x) for x in rng.split("-"))
        if all(lo <= s <= hi for s in seeds):
            return name
    return "?"


def main():
    out = ["# Results: perception-driven pipeline (legacy scene, weld-assist grasps)", "",
           "Generated by `python scripts/results_table.py` from the JSON files in `results/perception/`. "
           "**Pour mode**: *held*, arm B holds the mug while arm A pours; *set-down*, arm B sets the mug at the pour "
           "spot, moves clear and re-grasps it afterwards. **Poses**: *perception*, object poses from the CNN on the "
           "overhead and front cameras (`models/perception/posenet_legacy.pt`); *ground truth*, poses read from the "
           "simulator. In both, whether a gripper holds something and the executor's success checks come from the "
           "simulator. Ranges are Wilson 95 % intervals. Dev seeds were used for development; the test seeds were "
           "run once, with the configuration frozen.", "",
           "| Poses | Pour mode | Seeds (split) | Full task | 95 % CI | " + " | ".join(SUBGOALS) + " | Change |",
           "|---|---|---|---|---|" + "---|" * len(SUBGOALS) + "---|"]
    for f, note in ROWS:
        d = json.load(open(os.path.join(R, f)))
        s, eps = d["summary"], d["episodes"]
        seeds = [e["seed"] for e in eps]
        k, n = sum(bool(e["success"]) for e in eps), len(eps)
        lo, hi = wilson(k, n)
        mode = s.get("pour_mode") or ("set-down" if s.get("pour_release") else "held")
        poses = "perception" if s.get("perception") else "ground truth"
        sg = " | ".join(f"{s['subgoal_rates'][g] * 100:.0f} %" for g in SUBGOALS)
        out.append(f"| {poses} | {mode} | {min(seeds)}–{max(seeds)} ({split_of(seeds)}) | **{k} / {n}** | "
                   f"{lo * 100:.0f}–{hi * 100:.0f} % | {sg} | {note} (`{f}`) |")
    g = json.load(open(os.path.join(R, "gate_step2_calibrated_legacy.json")))
    out += ["", f"**Step-2 gate** (`gate_step2_calibrated_legacy.json`, rule: {g['rule']}): "
            f"{'passed' if g['passed'] else 'failed'}, pour mode {g['pour_mode']}, perception {g['perception']['k']} "
            f"/ {g['n']} against ground truth {g['truth']['k']} / {g['n']} ({g['gap_points']:.0f} points). "
            f"Drawer-opening estimate at each release: median error {g['drawer_audit']['abs_err_mm_median']:.1f} mm, "
            f"max {g['drawer_audit']['abs_err_mm_max']:.1f} mm over {g['drawer_audit']['n_releases']} releases.", ""]
    t = json.load(open(os.path.join(R, "test_perception_calibrated_setdown_legacy.json")))["episodes"]
    lat = sorted(x for e in t for x in (e.get("perception") or {}).get("latency_ms", []) or [])
    if lat:
        out.append(f"CNN latency on the test run (two cameras, {len(lat)} estimates): median "
                   f"{lat[len(lat) // 2]:.1f} ms, p95 {lat[int(len(lat) * 0.95)]:.1f} ms.")
        out.append("")
    s1 = json.load(open(os.path.join(R, "gate_step1_legacy.json")))
    out += ["**Step-1 perception gate** (`gate_step1_legacy.json`, rule: " + s1["gate_rule"] + "): "
            + ("passed" if s1["gate"]["passed"] else "failed") + ". Per object, grasp-point xy error median / p95 (mm): "
            + ", ".join(f"{o} {v['grasp_median']:.1f} / {v['grasp_p95']:.1f}" for o, v in s1["gate"].items()
                        if isinstance(v, dict)) + ".", "",
            "The strict droplet-pour metric (particles captured in the mug) is 0 % in every run above and is not "
            "used for success; a pour counts geometrically (see the README's Limitations).", ""]
    os.makedirs("docs", exist_ok=True)
    with open("docs/RESULTS.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
